from zoneinfo import ZoneInfo

from app.plans.dates import normalize_clock_minutes

WEEKDAYS = ('понедельник', 'вторник', 'среда', 'четверг', 'пятница', 'суббота', 'воскресенье')

def date_context(timezone, now=None):
    zone = ZoneInfo(timezone)
    current = (now or datetime.now(zone)).astimezone(zone)
    days = {name: (current.date() + timedelta(days=offset)).isoformat()
            for name, offset in [('сегодня', 0), ('завтра', 1), ('послезавтра', 2)]}
    return {
        'сейчас': current.isoformat(), 'часовой_пояс': timezone,
        'относительные_даты': days,
        'ближайшие_дни': [{'дата': (current.date() + timedelta(days=i)).isoformat(),
                         'день_недели': WEEKDAYS[(current.date() + timedelta(days=i)).weekday()]}
                        for i in range(8)]}

def normalize_transcript(text):
    # Only unambiguous duration expressions are rewritten deterministically.
    replacements = [(r'\b(?:на\s+)?полтора\s+часа\b', 'на 90 минут'),
                    (r'\bполчаса\b', '30 минут'),
                    (r'\bполторы\s+минуты\b', '90 секунд')]
    for pattern, replacement in replacements:
        text = re.sub(pattern, replacement, text, flags=re.IGNORECASE)
    text = re.sub(r'\bв[оа]лей\s*бол', lambda match: 'Волейбол' if match[0][0].isupper() else 'волейбол', text, flags=re.I)
    text = re.sub(r'\bтренеровк', lambda match: 'Тренировк' if match[0][0].isupper() else 'тренировк', text, flags=re.I)
    text = re.sub(r'(?<![\d-])([01]?\d|2[0-3])[-–]([0-5]\d)(?![\d-])', r'\1:\2', text)
    # GigaAM occasionally mixes written hours and stray syllables in a single
    # range. Repair known forms only when both endpoints are identifiable.
    text = re.sub(
        r'\bс\s+восемнад(?:цати|ти)\s+до\s+(?:девятнадцати|19(?:яна)?:0{1,2})(?![\w:])',
        'с 18:00 до 19:00', text, flags=re.I,
    )
    return normalize_clock_minutes(text)

